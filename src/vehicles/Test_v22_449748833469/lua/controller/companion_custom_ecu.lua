local function graphValue(points,x,extrapolate)
  local count=#points
  if x<=points[1][1] and not extrapolate then return points[1][2] end
  if x>=points[count][1] and not extrapolate then return points[count][2] end
  local low,high=1,count
  while high-low>1 do
    local mid=math.floor((low+high)/2)
    if x<points[mid][1] then high=mid else low=mid end
  end
  local a,b=points[low],points[high]
  return a[2]+(x-a[1])/(b[1]-a[1])*(b[2]-a[2])
end
