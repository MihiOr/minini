-- Bound-aware motor allocation. Pedals establish a force band, not an
-- equality that would immobilize vectoring at full motor/traction saturation:
-- gas permits less propulsion, brake permits less braking, coast stays zero.
-- Individual wheels may drive or regenerate under any pedal request.
-- The force band constrains only their combined longitudinal force.
local function allocate(base,lo,hi,weight,c,h,wantedForce,wantedMoment)
  local penalty,minForce,maxForce={},0,0
  for i=1,4 do
    penalty[i]=config.allocation_regularization/math.max(weight[i],.03)^2
    minForce=minForce+c[i]*lo[i];maxForce=maxForce+c[i]*hi[i]
  end
  wantedForce=clamp(wantedForce,minForce,maxForce)
  local floor=math.max(minForce,math.min(0,wantedForce))
  local ceiling=math.min(maxForce,math.max(0,wantedForce))
  -- Find the reachable yaw interval of the motor/grip box intersected with
  -- the pedal force band. Impossible yaw requests otherwise dominate the
  -- objective and spend the force budget on a slipping front wheel merely
  -- because its steered force has a longer yaw lever than the rear wheel.
  local minMoment,maxMoment=math.huge,-math.huge
  local function vertex(f)
    local force,moment=0,0
    for i=1,4 do force=force+c[i]*f[i];moment=moment+h[i]*f[i] end
    if force>=floor-1e-7 and force<=ceiling+1e-7 then
      minMoment=math.min(minMoment,moment);maxMoment=math.max(maxMoment,moment)
    end
  end
  for pattern=0,15 do
    local f,code={},pattern
    for i=1,4 do f[i]=code%2==0 and lo[i] or hi[i];code=math.floor(code/2) end
    vertex(f)
  end
  for free=1,4 do
    for pattern=0,7 do
      local f,code,force={},pattern,0
      for i=1,4 do
        if i~=free then
          f[i]=code%2==0 and lo[i] or hi[i];code=math.floor(code/2)
          force=force+c[i]*f[i]
        end
      end
      if math.abs(c[free])>1e-9 then
        for _,bound in ipairs({floor,ceiling}) do
          f[free]=(bound-force)/c[free]
          if f[free]>=lo[free]-1e-7 and f[free]<=hi[free]+1e-7 then vertex(f) end
        end
      end
    end
  end
  if minMoment<=maxMoment then wantedMoment=clamp(wantedMoment,minMoment,maxMoment) end
  local function cost(f)
    local forceError,momentError,value=-wantedForce,-wantedMoment,0
    for i=1,4 do
      forceError=forceError+c[i]*f[i];momentError=momentError+h[i]*f[i]
      value=value+penalty[i]*(f[i]-base[i])^2
    end
    return value+config.force_priority*forceError^2+config.moment_priority*momentError^2
  end
  local best={}
  for i=1,4 do best[i]=clamp(base[i],lo[i],hi[i]) end
  local bestCost=cost(best)
  local fw,mw=config.force_priority,config.moment_priority
  for pattern=0,80 do
    local code=pattern
    local free,f={},{}
    local rf,rm=-wantedForce,-wantedMoment
    local aa,bb,cc=0,0,0
    for i=1,4 do
      local state=code%3;code=math.floor(code/3)
      if state==1 then
        free[#free+1]=i;f[i]=base[i]
        aa=aa+c[i]^2/penalty[i];bb=bb+c[i]*h[i]/penalty[i];cc=cc+h[i]^2/penalty[i]
      else f[i]=state==0 and lo[i] or hi[i] end
      rf=rf+c[i]*f[i];rm=rm+h[i]*f[i]
    end
    local a,b,d,e=1+fw*aa,mw*bb,fw*bb,1+mw*cc
    local determinant=a*e-b*d
    local residualF,residualM=(e*rf-b*rm)/determinant,(a*rm-d*rf)/determinant
    for _,i in ipairs(free) do
      f[i]=base[i]-(fw*c[i]*residualF+mw*h[i]*residualM)/penalty[i]
    end
    local sum=0
    for i=1,4 do sum=sum+c[i]*f[i] end
    local feasible=true
    if sum<floor-1e-7 or sum>ceiling+1e-7 then
      if #free==0 then feasible=false
      else
        local bound=clamp(sum,floor,ceiling)
        local rhs=rf+wantedForce-bound
        local det=aa*(1+mw*cc)-mw*bb^2
        if det<=0 then feasible=false
        else
          local multiplier=((1+mw*cc)*rhs-mw*bb*rm)/det
          residualM=(aa*rm-bb*rhs)/det
          for _,i in ipairs(free) do
            f[i]=base[i]-(multiplier*c[i]+mw*h[i]*residualM)/penalty[i]
          end
        end
      end
    end
    sum=0
    for i=1,4 do
      if not finite(f[i]) or f[i]<lo[i]-1e-7 or f[i]>hi[i]+1e-7 then feasible=false end
      sum=sum+c[i]*f[i]
    end
    if sum<floor-1e-6 or sum>ceiling+1e-6 then feasible=false end
    if feasible then
      local value=cost(f)
      if value<bestCost then best,bestCost=f,value end
    end
  end
  return best
end

local function selectDirection(s,m,dt)
  if not config.autoDirectionEnabled then return s.gear>0 and 1 or (s.gear<0 and -1 or 0) end
  if not m.selectedGear then m.selectedGear=s.gear<0 and -1 or 1 end
  local stopped=math.abs(s.bodySpeed)<config.autoDirectionSpeed
  for _,name in ipairs(names) do
    if math.abs(s.wheelSpeed[name])>config.autoDirectionWheelSpeed then stopped=false end
  end
  local threshold=config.autoDirectionPedalThreshold
  local wanted
  if stopped and s.parkingBrake<=0.01 then
    if s.brake>threshold and s.throttle<=threshold then wanted=-1
    elseif s.throttle>threshold and s.brake<=threshold then wanted=1 end
  end
  if wanted and wanted~=m.selectedGear then
    if m.pendingGear~=wanted then m.pendingGear=wanted;m.directionHold=0 end
    m.directionHold=m.directionHold+dt
    if m.directionHold>=config.autoDirectionHoldSeconds then
      m.selectedGear=wanted;m.pendingGear=nil;m.directionHold=0
    end
  else m.pendingGear=nil;m.directionHold=0 end
  return m.selectedGear
end


-- Integrate the average three-axis gyro into a body-frame gravity direction.
-- Accelerometer alignment is used only at rest: lateral cornering force must
-- never be mistaken for gravity. No simulator orientation enters this observer.
local function updateAttitude(samples,s,m,dt)
  local p,q,r,ax,ay,az=0,0,0,0,0,0
  for _,imu in ipairs(samples) do
    p=p+(finite(imu.gyro.forward) and imu.gyro.forward or 0)
    q=q+(finite(imu.gyro.left) and imu.gyro.left or 0)
    r=r+imu.gyro.up
    ax=ax+imu.acceleration.forward;ay=ay+imu.acceleration.left;az=az+imu.acceleration.up
  end
  local n=#samples
  p,q,r,ax,ay,az=p/n,q/n,r/n,ax/n,ay/n,az/n
  local gx,gy,gz=m.gravityX or 0,m.gravityY or 0,m.gravityZ or -G
  local rate=math.sqrt(p*p+q*q+r*r)
  local norm=math.sqrt(ax*ax+ay*ay+az*az)
  local stationary=s.bodySpeed<.5 and rate<.15 and math.abs(norm-G)<.5
  if not m.attitudeInitialized and stationary and norm>1 then
    gx,gy,gz=-G*ax/norm,-G*ay/norm,-G*az/norm
    m.attitudeInitialized=true
  elseif rate>1e-9 then
    -- Rodrigues rotation: gravity rotates opposite to the sensor frame.
    local x,y,z=p/rate,q/rate,r/rate
    local c,si=math.cos(rate*dt),-math.sin(rate*dt)
    local dot=x*gx+y*gy+z*gz
    gx,gy,gz=gx*c+(y*gz-z*gy)*si+x*dot*(1-c),
      gy*c+(z*gx-x*gz)*si+y*dot*(1-c),
      gz*c+(x*gy-y*gx)*si+z*dot*(1-c)
  end
  if stationary and norm>1 then
    local k=1-math.exp(-dt/2)
    gx,gy,gz=gx+k*(-G*ax/norm-gx),gy+k*(-G*ay/norm-gy),gz+k*(-G*az/norm-gz)
  end
  local length=math.sqrt(gx*gx+gy*gy+gz*gz)
  gx,gy,gz=gx*G/length,gy*G/length,gz*G/length
  m.gravityX,m.gravityY,m.gravityZ=gx,gy,gz
  m.roll=math.atan2(-gy,-gz);m.pitch=math.asin(clamp(gx/G,-1,1))
  m.gyroAccelerationForward=(p-(m.gyroForward or p))/dt
  m.gyroAccelerationLeft=(q-(m.gyroLeft or q))/dt
  m.gyroForward,m.gyroLeft,m.gyroUp=p,q,r
  return gx,gy,gz
end

local function observe(s,m,dt)
  local samples,rates={},{}
  for _,n in ipairs(names) do
    local p=s.imu and s.imu[n]
    if p and p.valid and p.gyro and p.acceleration and p.offset and
      finite(p.gyro.up) and finite(p.acceleration.forward) and finite(p.acceleration.left) and
      finite(p.acceleration.up) and finite(p.offset.forward) and finite(p.offset.left) then
      samples[#samples+1]=p;rates[#rates+1]=p.gyro.up
    end
  end
  if #samples<3 then return false end
  local gravityX,gravityY,gravityZ=updateAttitude(samples,s,m,dt)
  local raw=m.gyroUp
  local filtered=1-math.exp(-dt/math.max(config.imu_filter_s,dt))
  local previous=m.yaw or 0
  m.yaw=previous+filtered*(raw-previous)
  m.yawAccel=(m.yawAccel or 0)+filtered*((m.yaw-previous)/dt-(m.yawAccel or 0))
  local xs,ys,up={},{},{}
  for _,p in ipairs(samples) do
    if math.abs(p.gyro.up-raw)<.35 then
      local x,y,z=p.offset.forward,p.offset.left,p.offset.up or 0
      local wx,wy,wz=m.gyroForward,m.gyroLeft,m.yaw
      local dot=wx*x+wy*y+wz*z
      local squared=wx*wx+wy*wy+wz*wz
      -- Remove tangential and centripetal acceleration at each IMU mount.
      local rotationalX=m.gyroAccelerationLeft*z-m.yawAccel*y+wx*dot-squared*x
      local rotationalY=m.yawAccel*x-m.gyroAccelerationForward*z+wy*dot-squared*y
      xs[#xs+1]=p.acceleration.forward+gravityX-rotationalX
      ys[#ys+1]=p.acceleration.left+gravityY-rotationalY
      up[#up+1]=p.acceleration.up
    end
  end
  if #xs<3 then return false end
  m.ax=(m.ax or 0)+filtered*(median(xs)-(m.ax or 0))
  m.ay=(m.ay or 0)+filtered*(median(ys)-(m.ay or 0))
  m.beta=m.beta or 0
  if s.bodySpeed>3 then
    local derivative=(m.ay*math.cos(m.beta)-m.ax*math.sin(m.beta))/((m.travelSign or 1)*s.bodySpeed)-m.yaw
    local beta=m.beta+dt*(derivative-config.observer_leak*m.beta)
    m.beta=math.atan2(math.sin(beta),math.cos(beta))
  else m.beta=m.beta*math.exp(-dt*3) end
  local grounded=median(up)>3
  m.observerRecovery=false;m.observerGpsBound=nil
  -- Signed chassis GPS speed is already used for travel direction. Its
  -- longitudinal component cannot exceed total speed, and |cos(beta)| is
  -- bounded by their ratio. This gives a magnitude bound, not a measured
  -- heading/slip-angle input. Vertical motion only loosens the bound.
  -- Never substitute wheel speed here: spinning wheels could falsely claim
  -- that a genuinely sideways car has recovered.
  if grounded and s.bodySpeed>3 and finite(s.travelSpeed) and
      math.abs(s.travelSpeed)<=s.bodySpeed*1.03 then
    local bound=math.acos(clamp(math.abs(s.travelSpeed)/s.bodySpeed,0,1))
    m.observerGpsBound=bound
    local discrepancy=math.abs(m.beta)-bound
    if discrepancy>config.observer_velocity_margin_deg*rad or
        (m.observerCorrecting and discrepancy>.25*rad) then
      m.observerInconsistent=(m.observerInconsistent or 0)+dt
      if m.observerInconsistent>=config.observer_consistency_hold_s then
        m.observerCorrecting=true
        local fraction=1-math.exp(-dt/config.observer_recovery_s)
        m.beta=m.beta+fraction*(clamp(m.beta,-bound,bound)-m.beta)
        m.observerRecovery=true
      end
    else m.observerInconsistent=0;m.observerCorrecting=false end
  else m.observerInconsistent=0;m.observerCorrecting=false end
  return grounded -- specific force: do not add yaw torque while airborne
end

-- One grip state feeds allocation bounds, correction distribution and telemetry.
-- A positive-slip cut restricts positive torque, not torque that slows that wheel.
local function estimateWheelGrip(slip,alpha,load,reserve,radius,positive,negative,m,i,dt)
  local capacity=1.3*load*math.sqrt(reserve)*radius
  for _,d in ipairs({1,-1}) do
    local scale=d>0 and m.positiveScale or m.negativeScale
    local directional=slip*d
    local excess=math.max(0,directional-config.slip_target)
    local recovery=config.slip_recovery_per_s*math.max(0,1-math.max(0,directional)/config.slip_target)
    -- Recognize an already-slipping wheel before assigning it new torque.
    local instant=config.slip_target/math.max(config.slip_target,directional)
    scale[i]=clamp(math.min(instant,scale[i]+dt*(recovery-config.slip_cut_gain*excess)),.03,1)
  end
  return {positiveNm=math.min(positive,capacity)*m.positiveScale[i],
    negativeNm=math.min(negative,capacity)*m.negativeScale[i],
    gripPositiveNm=capacity*m.positiveScale[i],gripNegativeNm=capacity*m.negativeScale[i],
    slipping=math.abs(slip)>config.slip_target+1e-6 or math.abs(alpha)>config.lateral_reserve_angle_deg*rad,
    positiveScale=m.positiveScale[i],negativeScale=m.negativeScale[i]}
end

return function(s,m)
  local incoming=finite(s.dt) and clamp(s.dt,0,.05) or 0
  m.elapsed=(m.elapsed or 0)+incoming
  if m.output and m.elapsed+1e-9<config.updateSeconds then return m.output end
  local dt=m.elapsed;m.elapsed=0
  if dt<=0 then return zeros(m.selectedGear or 1) end
  if not finite(s.bodySpeed) or s.bodySpeed<0 then return zeros(m.selectedGear or 1) end
  for _,n in ipairs(names) do
    if not s.wheelSpeed or not finite(s.wheelSpeed[n]) then return zeros(m.selectedGear or 1) end
  end
  local direction=selectDirection(s,m,dt)
  if m.lastDirection and direction~=m.lastDirection then
    m.previousOmega=nil;m.previousTorque=nil;m.beta=0;m.lateralMoment=0;m.previousTarget=0
    m.positiveScale=nil;m.negativeScale=nil
  end
  m.lastDirection=direction
  m.recoveryStop=false -- discard any automatic-stop latch from an older policy
  local gas,brake=clamp(s.throttle or 0,0,1),clamp(s.brake or 0,0,1)
  if direction<0 then gas,brake=brake,gas end
  local parking=clamp(s.parkingBrake or 0,0,1)
  local braking=brake -- parking brake is a physical wheel brake, never motor regen
  if parking>.01 then m.launch=false;m.armed=false end
  local wasLaunching=m.launch==true
  if m.launch and (not config.launchEnabled or direction~=1 or gas<.5 or braking>.01) then m.launch=false end
  if m.armed and (not config.launchEnabled or direction~=1 or gas<.5 or s.bodySpeed>2) then m.armed=false end
  local arm=config.launchEnabled and direction==1 and s.bodySpeed<1 and gas>.5 and brake>.5 and parking<=.01
  if arm and not m.armHeld and not wasLaunching then m.armed=true end
  m.armHeld=arm
  if m.armed and braking<=.01 then m.armed=false;m.launch=true;m.launchTime=0 end
  if m.launch then m.launchTime=(m.launchTime or 0)+dt end
  local ramp=1
  if m.launch and config.launchRampSeconds>0 then
    ramp=clamp(config.launchInitialTorque+(1-config.launchInitialTorque)*m.launchTime/config.launchRampSeconds,0,1)
  end
  if braking>.01 or parking>.01 or m.armed or direction==0 then gas=0 end
  gas=gas*ramp
  local travel=s.travelSpeed
  if not finite(travel) then
    local speeds={}
    for _,n in ipairs(names) do speeds[#speeds+1]=s.wheelSpeed[n] end
    travel=median(speeds) -- compatibility fallback until signed chassis GPS is available
  end
  local travelSign=math.abs(travel)>.2 and sign(travel) or (m.travelSign or direction)
  if m.travelSign and travelSign~=m.travelSign then
    m.beta=0;m.previousTarget=0;m.lateralMoment=0;m.previousOmega=nil
  end
  m.travelSign=travelSign
  local healthy=observe(s,m,dt)
  m.yaw=m.yaw or 0;m.yawAccel=m.yawAccel or 0;m.ax=m.ax or 0;m.ay=m.ay or 0;m.beta=m.beta or 0
  local enabled=config.vectoringEnabled and healthy and not m.armed and not s.calibrationActive and s.bodySpeed>3 and parking<=.01 and steeringCurve~=nil
  local g=s.geometry or {}
  local wb,tf,tr=g.wheelbase or 3,g.trackFront or 2,g.trackRear or 2
  local mass=g.mass or 710
  local frontFraction=g.cgFrontFraction or .48875687
  local height=g.cgHeight or .50134
  local inertia=g.yawInertia or 1146.791*(mass/710)*(wb/3)^2
  local a,b=wb*(1-frontFraction),wb*frontFraction
  local steer=clamp(s.steering or 0,-1,1)*config.steeringSign
  local lock=finite(s.steeringWheelLock) and s.steeringWheelLock>0 and s.steeringWheelLock or config.steeringWheelLockDegrees
  local curvature=steeringRequest(steer,lock)
  -- Infer low-speed rolling geometry from the same measured curvature, rather
  -- than combining a calibrated target with an unrelated 30-degree assumption.
  local angle=curvature and math.atan(wb*curvature) or steer*config.steeringAngleDegrees*rad
  local angles={0,0,0,0}
  if math.abs(angle)>1e-8 then
    local turning=wb/math.tan(angle)
    angles[1]=math.atan(wb/(turning-tf/2));angles[2]=math.atan(wb/(turning+tf/2))
  end
  local front=clamp(mass*G*frontFraction-mass*m.ax*height/wb,.02*mass*G,.98*mass*G)
  local rear=mass*G-front
  local fs,rs=mass*m.ay*height*frontFraction/tf,mass*m.ay*height*(1-frontFraction)/tr
  local load={math.max(1,front/2-fs),math.max(1,front/2+fs),math.max(1,rear/2-rs),math.max(1,rear/2+rs)}
  local total=load[1]+load[2]+load[3]+load[4]
  local base,lo,hi,weights,c,h,radius,omega,drive,regen,slips,reserves,alphas={},{},{},{},{},{},{},{},{},{},{},{},{}
  local gripPositive,gripNegative,gripStates={},{},{}
  m.positiveScale=m.positiveScale or {1,1,1,1};m.negativeScale=m.negativeScale or {1,1,1,1}
  m.previousTorque=m.previousTorque or {0,0,0,0}
  local ux=travelSign*s.bodySpeed*math.cos(m.beta)
  local uy=travelSign*s.bodySpeed*math.sin(m.beta)
  local longitudinalMoment=0
  for i,n in ipairs(names) do
    load[i]=load[i]*mass*G/total
    local limit=s.motorLimits and s.motorLimits[n] or {}
    radius[i]=finite(limit.radius) and limit.radius>.05 and limit.radius or .313
    omega[i]=s.wheelSpeed[n]/radius[i]
    drive[i]=math.max(0,limit.drive or 737.24495)
    regen[i]=math.max(0,limit.regen or 589.79596*clamp(math.abs(omega[i])*9.549296586/30,0,1))
    local x=i<=2 and a or -b
    local y=(i%2==1 and 1 or -1)*(i<=2 and tf or tr)/2
    c[i]=math.cos(angles[i]);h[i]=x*math.sin(angles[i])-y*c[i]
    if m.previousOmega and healthy then
      local prior=m.previousTorque[i]
      local maximum=prior*omega[i]<0 and regen[i] or drive[i]
      prior=clamp(prior,-maximum,maximum)
      local force=(prior-(limit.inertia or .611)*(omega[i]-m.previousOmega[i])/dt)/radius[i]
      longitudinalMoment=longitudinalMoment+h[i]*force
    end
    local road=(ux-m.yaw*y)*c[i]+(uy+m.yaw*x)*math.sin(angles[i])
    local lateral=-(ux-m.yaw*y)*math.sin(angles[i])+(uy+m.yaw*x)*c[i]
    local alpha=math.atan2(lateral,math.max(math.abs(road),.8))
    local reserve=math.max(config.minimum_lateral_reserve,1/(1+(math.abs(alpha)/(config.lateral_reserve_angle_deg*rad))^4))
    reserves[i]=reserve;alphas[i]=alpha
    local slip=(s.wheelSpeed[n]-road)/math.max(math.abs(road),.8);slips[i]=slip
    -- Directional longitudinal grip is represented by the solve's bounds.
    -- Do not penalize both directions for slip that only limits one of them.
    weights[i]=math.max(.03,reserve*load[i]/(mass*G/4))
    local positive=omega[i]<0 and regen[i] or drive[i]
    local negative=omega[i]>=0 and regen[i] or drive[i]
    -- A stationary shaft can be driven in either direction. Its zero-RPM
    -- regen envelope is zero, but that must not prevent starting in Reverse.
    if math.abs(omega[i])<.01 then negative=drive[i] end
    local grip=estimateWheelGrip(slip,alpha,load[i],reserve,radius[i],positive,negative,m,i,dt)
    gripStates[i]=grip
    gripPositive[i],gripNegative[i]=grip.gripPositiveNm,grip.gripNegativeNm
    -- MiTVS solves all four motors inside these known grip/anti-lock bounds.
    -- There is no later TC multiplier that can veto an allocated correction.
    lo[i],hi[i]=-grip.negativeNm/radius[i],grip.positiveNm/radius[i]
    local lower,upper=lo[i],hi[i]
    local slew=config.torque_slew_nm_s*dt/radius[i]
    -- Always allow zero immediately on pedal release/change. Slew must not
    -- force old propulsion while coasting, or old regeneration under gas.
    lo[i]=math.min(0,math.max(lower,m.previousTorque[i]/radius[i]-slew))
    hi[i]=math.max(0,math.min(upper,m.previousTorque[i]/radius[i]+slew))
    if lo[i]>hi[i] then lo[i],hi[i]=lower,upper end
    base[i]=clamp(direction*(gas*drive[i]-braking*regen[i])/radius[i],lo[i],hi[i])
  end
  if healthy and m.previousOmega then
    local fraction=1-math.exp(-dt/math.max(config.disturbance_filter_s,dt))
    m.lateralMoment=(m.lateralMoment or 0)+fraction*(inertia*m.yawAccel-longitudinalMoment-(m.lateralMoment or 0))
  end
  local requestedSteer=steer
  local target=(curvature or 0)*travelSign*s.bodySpeed*config.steeringOutputMultiplier
  local maximum=config.max_lateral_g*G/math.max(s.bodySpeed,2)
  target=clamp(target,-maximum,maximum)
  local targetBeta=math.atan(b*target/(travelSign*math.max(s.bodySpeed,.1)))
  local betaError=m.beta-targetBeta
  local derivative=(target-(m.previousTarget or 0))/dt;m.previousTarget=target
  local force,moment=0,0
  for i=1,4 do force=force+c[i]*base[i];moment=moment+h[i]*base[i] end
  local assistance=0
  local yawRateError=target-m.yaw
  local yawCorrection=yawErrorCorrection(deadband(yawRateError,config.yawErrorDeadbandDegrees*rad))
  if enabled then
    local error=yawRateError
    local severity=math.max(
      smoothstep((math.abs(error)/rad-config.yawErrorDeadbandDegrees)/
        (config.fullAssistYawErrorDegrees-config.yawErrorDeadbandDegrees)),
      smoothstep((math.abs(betaError)/rad-config.sideslipErrorDeadbandDegrees)/
        (config.fullAssistSideslipDegrees-config.sideslipErrorDeadbandDegrees)))
    local activity=math.max(
      smoothstep(math.abs(error)/(config.yawErrorDeadbandDegrees*rad)),
      smoothstep(math.abs(betaError)/(config.sideslipErrorDeadbandDegrees*rad)))
    assistance=(config.minimumAssistGain+(1-config.minimumAssistGain)*severity)*activity
    -- Gate the entire correction, including disturbance feedforward: otherwise
    -- small straight-line IMU fluctuations can still create alternating torque.
    -- Error thresholds apply equally at every steering input. The measured
    -- curvature table alone maps steering input to the requested yaw.
    local correctedBeta=deadband(betaError,config.sideslipErrorDeadbandDegrees*rad)
    local correction=inertia*(derivative+yawCorrection-config.yaw_accel_damping*m.yawAccel+
      config.sideslip_gain*clamp(correctedBeta,-.6,.6))*clamp((s.bodySpeed-1)/3,0,1)-(m.lateralMoment or 0)
    moment=moment+assistance*(correction-moment)
    -- If added torque is unavailable on one side, release more torque on
    -- the opposite side. Never exceed motor or TC/anti-lock envelopes.
  end
  local f={}
  if enabled then f=allocate(base,lo,hi,weights,c,h,force,moment)
  else for i=1,4 do f[i]=clamp(base[i],lo[i],hi[i]) end end
  if m.armed then for i=1,4 do f[i]=0 end end
  local out=zeros(direction)
  out.launchActive=m.launch==true;out.launchArmed=m.armed==true
  local status={active=false,axle='all',mode='misim',yawRate=m.yaw,targetYawRate=target,
    yawRateError=yawRateError,yawCorrection=yawCorrection,
    pedalRequest=(m.armed or parking>.01 or direction==0) and 0 or clamp(gas-braking,-1,1),
    wheelCorrection={},
    rollEstimate=m.roll,pitchEstimate=m.pitch,
    sideslipEstimate=m.beta,assistanceGain=assistance,requestedSteering=requestedSteer,availability={},estimatedSlip={},estimatedLateralSlipDegrees={},gripReserve={},estimatedWheelAngles={},torqueLimits={},torqueHeadroom={},requestedYawMoment=moment,
    requestedForce=force,allocatedForce=0,allocatedYawMoment=0,stabilityDeceleration=0,
    recoveryStop=false,sensorHealthy=healthy,travelDirection=travelSign,
    steeringCalibrated=steeringCurve~=nil,requestedCurvature=curvature or 0,
    naturalSideslipTarget=targetBeta,sideslipError=betaError,estimatedLateralMoment=m.lateralMoment or 0,
    observerRecoveryActive=m.observerRecovery==true,
    observerGpsBoundDegrees=m.observerGpsBound and m.observerGpsBound/rad or nil}
  local correctionTotal=0
  for i,n in ipairs(names) do
    local torque=f[i]*radius[i]
    if torque*omega[i]<0 and regen[i]>0 then
      out.regen[n]=clamp(math.abs(torque)/regen[i],0,1)
    elseif drive[i]>0 then out[n]=clamp(torque/drive[i],-1,1) end
    m.previousTorque[i]=torque
    -- Diagnostics describe the software allocation, never measured shaft torque.
    local delta=enabled and not m.armed and (f[i]-base[i]) or 0
    local contribution=h[i]*delta
    correctionTotal=correctionTotal+math.abs(contribution)
    local motorLimit=torque*omega[i]<0 and regen[i] or drive[i]
    local gripLimit=torque<0 and gripNegative[i] or gripPositive[i]
    status.wheelCorrection[n]={yawMomentNm=contribution,deltaTorqueNm=delta*radius[i],
      commandedTorqueNm=torque,motorLimitNm=motorLimit,gripLimitNm=gripLimit,
      motorUse=motorLimit>1e-6 and clamp(torque/motorLimit,-1,1) or 0,
      gripUse=gripStates[i].slipping and 1 or (gripLimit>1e-6 and clamp(math.abs(torque)/gripLimit,0,1) or 0),
      longitudinalSlip=math.abs(slips[i]),lateralSlip=math.abs(alphas[i])/rad,
      slipping=gripStates[i].slipping,positiveSlipScale=gripStates[i].positiveScale,
      negativeSlipScale=gripStates[i].negativeScale,
      positiveLimitNm=gripStates[i].positiveNm,negativeLimitNm=gripStates[i].negativeNm}
    status.availability[n]=weights[i];status.estimatedSlip[n]=slips[i];status[n]=weights[i]
    status.gripReserve[n]=reserves[i];status.estimatedLateralSlipDegrees[n]=alphas[i]/rad
    status.estimatedWheelAngles[n]=angles[i]
    status.torqueLimits[n]={minimumNm=lo[i]*radius[i],maximumNm=hi[i]*radius[i],
      positiveSlipScale=m.positiveScale[i],negativeSlipScale=m.negativeScale[i]}
    status.torqueHeadroom[n]={increaseNm=math.max(0,hi[i]*radius[i]-torque),
      decreaseNm=math.max(0,torque-lo[i]*radius[i])}
    status.allocatedForce=status.allocatedForce+c[i]*f[i]
    status.allocatedYawMoment=status.allocatedYawMoment+h[i]*f[i]
    if enabled and math.abs(f[i]-base[i])>1 then status.active=true end
  end
  for _,n in ipairs(names) do
    local row=status.wheelCorrection[n]
    row.share=correctionTotal>1e-6 and math.abs(row.yawMomentNm)/correctionTotal or 0
  end
  status.pedalForceDifference=status.allocatedForce-force
  status.yawMomentError=moment-status.allocatedYawMoment
  m.previousOmega=omega
  out.vectoring=status;m.output=out
  return out
end
