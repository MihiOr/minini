-- Shared by the in-game adapter and Companion's offline checker (Lua 5.1).
local function boundedCall(fn, ...)
  local previous, mask, count = debug.gethook()
  -- MiSim's bounded 81-case motor allocator executes at 100 Hz. Keep an
  -- instruction ceiling large enough for that finite solve, still trapping loops.
  debug.sethook(function() error('Custom controller instruction limit exceeded') end, '', 150000)
  local ok, result = pcall(fn, ...)
  debug.sethook(previous, mask, count)
  if not ok then error(result) end
  return result
end
local function loadUser(source)
  local fn, err = loadstring(source, '@custom_motor_control.lua')
  if not fn then error(err) end
  local safeMath = {}
  for k,v in pairs(math) do safeMath[k]=v end
  setfenv(fn, {math=safeMath, pairs=pairs, ipairs=ipairs, next=next,
    tonumber=tonumber, tostring=tostring, type=type, assert=assert, error=error,
    select=select, unpack=unpack})
  if jit then jit.off(fn, true) end
  local user = boundedCall(fn)
  assert(type(user)=='function', 'File must return function(s, memory)')
  if jit then jit.off(user, true) end
  return user
end
local function evaluateUser(fn, state, memory)
  local output = boundedCall(fn, state, memory)
  assert(type(output)=='table', 'Return a table with FL, FR, RL, RR')
  for _, wheel in ipairs({'FL','FR','RL','RR'}) do
    local value = output[wheel]
    assert(type(value)=='number' and value==value and value>=-1 and value<=1,
      wheel..' torque must be a finite number between -1 and 1')
  end
  for _, key in ipairs({'launchActive','launchArmed'}) do
    assert(output[key]==nil or type(output[key])=='boolean', key..' must be boolean')
  end
  assert(output.gear==nil or output.gear==-1 or output.gear==0 or output.gear==1,
    'gear must be -1 (R), 0 (N), or 1 (D)')
  if output.regen~=nil then
    assert(type(output.regen)=='table', 'regen must be a table with FL, FR, RL, RR')
    for _, wheel in ipairs({'FL','FR','RL','RR'}) do
      local value=output.regen[wheel]
      assert(type(value)=='number' and value==value and value>=0 and value<=1,
        wheel..' regen must be a finite number between 0 and 1')
      assert(value==0 or output[wheel]==0, wheel..' cannot request drive and regen together')
    end
  end
  return output
end

-- Virtual IMU hardware model. Geometry is internal to the sensor only.
-- The user's ECU receives specific force and angular rate, never pose/slip angles.
local function createIMUSampler(config)
  if not config or not config.mounts or not v or not v.data then return nil end
  local ids={}
  -- BeamNG adds section metadata and anonymous generated nodes to this table.
  for key,node in pairs(v.data.nodes or {}) do
    if type(node)=='table' and type(node.name)=='string' then
      ids[node.name]=node.cid or key
    end
  end
  local state={}
  for name,mount in pairs(config.mounts) do
    local nodes={}
    for i,node in ipairs(mount.nodes) do nodes[i]=ids[node] end
    if nodes[1]==nil or nodes[2]==nil or nodes[3]==nil then return nil end
    state[name]={nodes=nodes,mount=mount}
  end
  local function reset()
    for _,sensor in pairs(state) do sensor.previous=nil end
  end
  local function sample(dt)
    local out={}
    for name,sensor in pairs(state) do
      local mount=sensor.mount
      local p=obj:getNodePosition(sensor.nodes[1])
      local edge=obj:getNodePosition(sensor.nodes[2])-p
      local other=obj:getNodePosition(sensor.nodes[3])-p
      local normal=edge:cross(other)
      if edge:length()<.05 or normal:length()<.01 or dt<=0 or dt>.1 then
        out[name]={valid=false};sensor.previous=nil
      else
        edge:normalize();normal:normalize()
        local side=normal:cross(edge)
        local function basis(c) return edge*c[1]+normal*c[2]+side*c[3] end
        local f,l,u=basis(mount.forward),basis(mount.left),basis(mount.up)
        local velocity=obj:getNodeVelocityVector(sensor.nodes[1])
        local previous=sensor.previous
        if previous then
          -- Frame increments simulate a rate gyro, not a heading-angle input.
          local omega=(previous.f:cross(f)+previous.l:cross(l)+previous.u:cross(u))*(.5/dt)
          local gravity=obj:getGravityVector()
          local force=(velocity-previous.velocity)*(1/dt)-gravity
          out[name]={valid=true,acceleration={forward=force:dot(f),left=force:dot(l),up=force:dot(u)},
            gyro={forward=omega:dot(f),left=omega:dot(l),up=omega:dot(u)},
            velocity={forward=velocity:dot(f),left=velocity:dot(l),up=velocity:dot(u)},offset=mount.offset}
        else out[name]={valid=false} end
        sensor.previous={f=f,l=l,u=u,velocity=velocity}
      end
    end
    return out
  end
  return {sample=sample,reset=reset}
end

