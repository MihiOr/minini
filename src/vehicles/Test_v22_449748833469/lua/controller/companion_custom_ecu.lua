local function median(t)
  for i=2,#t do local v=t[i];local j=i-1
    while j>0 and t[j]>v do t[j+1]=t[j];j=j-1 end
    t[j+1]=v
  end
  local mid=math.floor((#t+1)/2)
  return #t%2==0 and (t[mid]+t[mid+1])/2 or t[mid]
end
